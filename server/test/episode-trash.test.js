const { test } = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const { PGlite } = require('@electric-sql/pglite');
const { initOutreachDB } = require('../outreach-schema');
const { initEpisodeTrash, createEpisodeTrashRouter } = require('../episode-trash');
test('sample Trash preserves related history and profiles and restores without restarting sends', async () => {
  const db = new PGlite(); let server;
  try {
    await db.exec(`CREATE TABLE admins(id INTEGER PRIMARY KEY); INSERT INTO admins VALUES(1);
      CREATE TABLE episodes(id INTEGER PRIMARY KEY,episode_number INTEGER UNIQUE,title TEXT,is_silent BOOLEAN,is_active BOOLEAN,is_registration_open BOOLEAN,event_date TIMESTAMP);
      CREATE TABLE students(id INTEGER PRIMARY KEY,email TEXT);
      CREATE TABLE episode_registrations(id INTEGER PRIMARY KEY,episode_id INTEGER REFERENCES episodes(id),student_id INTEGER REFERENCES students(id));
      CREATE TABLE zoom_registration_jobs(registration_id INTEGER PRIMARY KEY REFERENCES episode_registrations(id) ON DELETE CASCADE,status TEXT,join_url TEXT);
      INSERT INTO episodes VALUES(16,16,'Zoom sample',TRUE,TRUE,TRUE,'2026-10-27'),(17,17,'Sender sample',TRUE,TRUE,TRUE,'2026-10-29'),(18,18,'Real workshop',FALSE,TRUE,TRUE,'2026-10-30');
      INSERT INTO students VALUES(1,'test@example.com');
      INSERT INTO episode_registrations VALUES(101,16,1),(102,18,1);
      INSERT INTO zoom_registration_jobs VALUES(101,'registered','https://zoom.example/private');`);
    await initOutreachDB(db); await initEpisodeTrash(db); await initEpisodeTrash(db);
    const campaign='11111111-1111-4111-8111-111111111111', batch='22222222-2222-4222-8222-222222222222';
    await db.query(`INSERT INTO invite_campaigns(id,episode_id,subject,body,batch_size,interval_minutes,status) VALUES($1,16,'Support','Body',1,15,'running')`,[campaign]);
    await db.query(`INSERT INTO invite_batches(id,campaign_id,status,provider_diagnostic) VALUES($1,$2,'review','{"http_status":403,"response_body":"evidence"}')`,[batch,campaign]);
    await db.query('INSERT INTO invite_recipients(campaign_id,batch_id,email) VALUES($1,$2,$3)',[campaign,batch,'test@example.com']);
    await db.query('INSERT INTO invite_delivery_imports(campaign_id,row_count) VALUES($1,0)',[campaign]);
    await db.exec(`INSERT INTO attendance_syncs(episode_id,meeting_uuid,source) VALUES(16,'uuid','zoom');
      INSERT INTO attendance_participants(id,episode_id,registration_id,duration_seconds) VALUES('p1',16,101,1800);
      INSERT INTO attendance_overrides(registration_id,status,note) VALUES(101,'present','Reviewed');
      INSERT INTO attendance_audit(episode_id,registration_id,action,detail) VALUES(16,101,'override','Reviewed');
      INSERT INTO attendance_tasks(episode_id) VALUES(16);
      INSERT INTO invite_suppressions VALUES('optout@example.com','unsubscribed',NOW());`);
    const app=express();app.use(express.json());app.use('/api/admin',createEpisodeTrashRouter({pool:{connect:async()=>({query:(...a)=>db.query(...a),release(){}})},
      authenticateToken:(req,res,next)=>{if(req.headers.authorization!=='Bearer test')return res.status(401).json({success:false});req.user={id:1};next();}}));
    server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
    const base=`http://127.0.0.1:${server.address().port}/api/admin`;
    async function request(path,method='GET',body,auth=true){const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(auth?{Authorization:'Bearer test'}:{})},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,body:await r.json()};}
    assert.equal((await request('/episode-trash','GET',null,false)).status,401);
    assert.equal((await request('/episodes/bad/trash-preview')).status,400);
    assert.equal((await request('/episodes/18/trash-preview')).status,409);
    let p=(await request('/episodes/16/trash-preview')).body;
    assert.equal(p.counts.episode_registrations,1);assert.equal(p.counts.invite_campaigns,1);
    assert.doesNotMatch(JSON.stringify(p),/test@example|private|response_body/);
    const remove=()=>request('/episodes/16/trash','POST',{confirmation:'TRASH EPISODE 16',fingerprint:p.fingerprint});
    assert.equal((await request('/episodes/16/trash','POST',{confirmation:'TRASH EPISODE 17',fingerprint:p.fingerprint})).status,409);
    await db.exec('UPDATE attendance_tasks SET attempts=1 WHERE episode_id=16');
    assert.equal((await remove()).status,409);
    p=(await request('/episodes/16/trash-preview')).body;
    await db.exec('CREATE TABLE future_dependencies(episode_id INTEGER REFERENCES episodes(id) ON DELETE CASCADE); INSERT INTO future_dependencies VALUES(16)');
    assert.equal((await remove()).status,409);assert.equal((await db.query('SELECT * FROM episode_trash')).rows.length,0);
    await db.exec('DROP TABLE future_dependencies');
    await db.exec(`CREATE FUNCTION reject_sample_delete() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'injected delete failure'; END $$;
      CREATE TRIGGER reject_sample_delete BEFORE DELETE ON episodes FOR EACH ROW EXECUTE FUNCTION reject_sample_delete();`);
    assert.equal((await remove()).status,500);
    assert.equal((await db.query('SELECT * FROM episode_trash')).rows.length,0);
    assert.equal((await db.query('SELECT * FROM episode_registrations WHERE episode_id=16')).rows.length,1);
    assert.equal((await db.query('SELECT * FROM invite_batches')).rows.length,1);
    await db.exec('DROP TRIGGER reject_sample_delete ON episodes; DROP FUNCTION reject_sample_delete()');
    const moved=await remove();assert.equal(moved.status,200);
    assert.equal((await db.query('SELECT * FROM episodes WHERE id=16')).rows.length,0);
    assert.equal((await db.query('SELECT * FROM students')).rows.length,1);
    assert.equal((await db.query('SELECT * FROM episode_registrations WHERE episode_id=18')).rows.length,1);
    assert.equal((await db.query('SELECT * FROM invite_suppressions')).rows.length,1);
    const listing=(await request('/episode-trash')).body;
    assert.equal(listing.data.length,1);assert.doesNotMatch(JSON.stringify(listing),/test@example|private|response_body/);
    await db.exec("INSERT INTO episodes VALUES(19,16,'Reused number',FALSE,TRUE,TRUE,'2026-10-30')");
    const restore=()=>request(`/episode-trash/${moved.body.trash_id}/restore`,'POST');
    assert.equal((await restore()).status,409);
    await db.exec('DELETE FROM episodes WHERE id=19');assert.equal((await restore()).status,200);
    const restored=(await db.query('SELECT * FROM episodes WHERE id=16')).rows[0];
    assert.equal(restored.is_active,false);assert.equal(restored.is_registration_open,false);
    assert.equal((await db.query('SELECT * FROM invite_campaigns')).rows[0].status,'paused');
    assert.equal((await db.query('SELECT * FROM attendance_tasks')).rows[0].status,'paused');
    assert.equal((await db.query('SELECT * FROM invite_batches')).rows[0].provider_diagnostic.response_body,'evidence');
    assert.equal((await db.query('SELECT * FROM zoom_registration_jobs')).rows[0].join_url,'https://zoom.example/private');
    assert.equal((await db.query('SELECT * FROM attendance_overrides')).rows.length,1);
    assert.equal((await restore()).status,404);assert.equal((await request('/episode-trash')).body.data.length,0);
  } finally {if(server)await new Promise(r=>server.close(r));await db.close();}
});
